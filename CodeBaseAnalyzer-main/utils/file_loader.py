# ── Helpers ───────────────────────────────────────────────────────────────────

def _is_excluded_path(path: str) -> bool:
    norm  = path.replace("\\", "/")
    parts = norm.split("/")
    for part in parts:
        if part in EXCLUDED_DIRS:
            return True
        if part.lower() in EXCLUDED_PATH_SEGMENTS:
            return True
    return False


def _is_excluded_filename(filename: str) -> bool:
    # ── Java ──────────────────────────────────────────────────────────────────
    if filename.endswith(".java"):
        for suffix in JAVA_EXCLUDED_SUFFIXES:
            if filename.endswith(suffix):
                return True
        for prefix in JAVA_EXCLUDED_PREFIXES:
            if filename.startswith(prefix):
                return True

    # ── Python ────────────────────────────────────────────────────────────────
    elif filename.endswith(".py"):
        if filename in PYTHON_EXCLUDED_FILENAMES:
            return True
        for prefix in PYTHON_EXCLUDED_PREFIXES:
            if filename.startswith(prefix):
                return True
        for suffix in PYTHON_EXCLUDED_SUFFIXES:
            if filename.endswith(suffix):
                return True

    # ── JavaScript / JSX ──────────────────────────────────────────────────────
    elif filename.endswith((".js", ".jsx")):
        if filename in JS_EXCLUDED_FILENAMES:
            return True
        for suffix in JS_EXCLUDED_SUFFIXES:
            if filename.endswith(suffix):
                return True

    # ── C# ────────────────────────────────────────────────────────────────────
    elif filename.endswith(".cs"):
        if filename in CS_EXCLUDED_FILENAMES:
            return True
        for suffix in CS_EXCLUDED_SUFFIXES:
            if filename.endswith(suffix):
                return True
        for prefix in CS_EXCLUDED_PREFIXES:
            if filename.startswith(prefix):
                return True

    return False


# ── Public API ────────────────────────────────────────────────────────────────

def load_code_files(root_dir: str) -> list[tuple[str, str]]:
    """
    Walk *root_dir* and return (path, source_code) tuples for every
    production Java, Python, JavaScript, JSX, and C# source file.

    Excluded:
      • Directories in EXCLUDED_DIRS / EXCLUDED_PATH_SEGMENTS
        (pruned at traversal time — never descended into)
      • Test / migration / config / generated files by name convention
      • Unreadable files (silently skipped)
    """
    files = []

    for root, dirs, filenames in os.walk(root_dir):
        dirs[:] = [
            d for d in dirs
            if d not in EXCLUDED_DIRS
            and d.lower() not in EXCLUDED_PATH_SEGMENTS
        ]

        for filename in filenames:
            if not filename.endswith((".java", ".py", ".js", ".jsx", ".cs")):
                continue

            if _is_excluded_filename(filename):
                continue

            full_path = os.path.join(root, filename)

            if _is_excluded_path(full_path):
                continue

            try:
                with open(full_path, "r", encoding="utf-8", errors="ignore") as f:
                    source = f.read()
                files.append((full_path, source))
            except Exception:
                continue

    return files